import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import asc from "assemblyscript/asc"

// Keep the AssemblyScript source out of TypeScript's normal compilation.
const directory = await mkdtemp(join(tmpdir(), "tiny-hypergraph-kernel-"))
try {
  const source = join(directory, "regionCostKernel.ts")
  const output = join(directory, "regionCostKernel.wasm")
  await writeFile(source, await readFile(new URL("./regionCostKernel.as", import.meta.url), "utf8"))
  // Never enable fastMath: JavaScript-compatible floating-point order is required.
  const result = await asc.main([source, "--outFile", output, "--optimize", "--runtime", "stub", "--noAssert"])
  if (result.error) throw result.error
  const bytes = await readFile(output)
  await writeFile(new URL("../../lib/parallel/regionCostKernelBytes.ts", import.meta.url),
    `// Generated by bun run build:region-cost-kernel. Do not edit.\nexport const regionCostKernelBytes = new Uint8Array([${Array.from(bytes).join(",")}])\n`)
} finally {
  await rm(directory, { recursive: true, force: true })
}
